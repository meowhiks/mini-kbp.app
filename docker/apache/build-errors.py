def main() -> None:
    out_dir = Path(__file__).resolve().parent / "errors"
    out_dir.mkdir(parents=True, exist_ok=True)
    for code, desc in ERRORS.items():
        html = TEMPLATE.format(code=code, desc=desc.replace('"', "&quot;"))
        (out_dir / f"{code}.html").write_text(html, encoding="utf-8")
    print(f"Generated {len(ERRORS)} error pages in {out_dir}")


if __name__ == "__main__":
    main()
